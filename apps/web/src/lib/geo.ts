/** Fictitious AROME terrain height (m). */
export function relief(la: number, lo: number): number {
  let h = 110 + 40 * Math.sin(la * 3.1) * Math.cos(lo * 2.3);
  MT.forEach(([a, b, H, sa, sb]) => (h += H * Math.exp(-(((la - a) / sa) ** 2 + ((lo - b) / sb) ** 2))));
  h += 50 * Math.sin(la * 41) * Math.cos(lo * 37);
  return Math.max(5, h);
}

export function inPoly(la: number, lo: number, poly: Poly): boolean {
  let c = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [a1, o1] = poly[i]!,
      [a2, o2] = poly[j]!;
    if (a1 > la !== a2 > la && lo < ((o2 - o1) * (la - a1)) / (a2 - a1) + o1) c = !c;
  }
  return c;
}

export const inDomain = (la: number, lo: number) => la >= DOM.la0 && la <= DOM.la1 && lo >= DOM.lo0 && lo <= DOM.lo1;

/** Shared places are shown 2 to 4 AROME cells away from their true position, always at the same spot. */
export const CELL = 0.025;
export function fuzz(la: number, lo: number): [number, number] {
  const h = hash(la.toFixed(4) + "," + lo.toFixed(4)),
    a = (h % 360) * D2R,
    d = (2 + ((h >> 3) % 3)) * CELL;
  return [la + d * Math.sin(a), lo + (d * Math.cos(a)) / Math.cos(la * D2R)];
}

