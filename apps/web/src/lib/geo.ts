/** Degrees decimal or degrees-minutes-seconds, with N/S/E/W (or O). */
export function parseCoord(s: string, lat: boolean): number | null {
  s = (s || "").trim().toUpperCase().replace(/,/g, ".");
  if (!s) return null;
  const sg = /[SWO]$|^[SWO]|^-/.test(s) ? -1 : 1;
  const n = s.match(/\d+(\.\d+)?/g);
  if (!n || n.length > 3) return null;
  const v = sg * (+n[0]! + +(n[1] || 0) / 60 + +(n[2] || 0) / 3600);
  if (n.length > 1 && (+n[1]! >= 60 || +(n[2] || 0) >= 60)) return null;
  return isFinite(v) && Math.abs(v) <= (lat ? 90 : 180) ? v : null;
}

